"""Generate the README header, ``docs/assets/pyamp-header.svg``.

    uv run python docs/make_header.py

"PyAmp" is figlet's ANSI Shadow font, drawn as blocks and line segments rather
than SVG text, so it looks the same whatever fonts the viewer has.
"""

from __future__ import annotations

from pathlib import Path

OUT = Path(__file__).resolve().parent / "assets" / "pyamp-header.svg"

ART = """\
██████╗ ██╗   ██╗ █████╗ ███╗   ███╗██████╗
██╔══██╗╚██╗ ██╔╝██╔══██╗████╗ ████║██╔══██╗
██████╔╝ ╚████╔╝ ███████║██╔████╔██║██████╔╝
██╔═══╝   ╚██╔╝  ██╔══██║██║╚██╔╝██║██╔═══╝
██║        ██║   ██║  ██║██║ ╚═╝ ██║██║
╚═╝        ╚═╝   ╚═╝  ╚═╝╚═╝     ╚═╝╚═╝"""

# Palette: the app icon's.
SLATE, LCD, GREEN, SHADOW, GOLD, DIM = (
    "#2a2c3a",
    "#08090b",
    "#22e06b",
    "#1d6e40",
    "#d4ac4a",
    "#8fd6a8",
)
CELL_W, CELL_H = 12, 22
ART_X, ART_Y = 56, 78
LINE = 4  # shadow stroke width

#: Box-drawing characters as line segments within a cell, as (x1, y1, x2, y2) in 0..1.
SEGMENTS = {
    "═": [(0, 0.5, 1, 0.5)],
    "║": [(0.5, 0, 0.5, 1)],
    "╔": [(1, 0.5, 0.5, 0.5), (0.5, 0.5, 0.5, 1)],
    "╗": [(0, 0.5, 0.5, 0.5), (0.5, 0.5, 0.5, 1)],
    "╚": [(0.5, 0, 0.5, 0.5), (0.5, 0.5, 1, 0.5)],
    "╝": [(0.5, 0, 0.5, 0.5), (0.5, 0.5, 0, 0.5)],
}

#: Spectrum bars: (resting height, animation duration s, delay s).
BARS = [
    (46, 0.9, 0.0),
    (72, 1.1, 0.2),
    (60, 0.8, 0.1),
    (88, 1.3, 0.3),
    (70, 1.0, 0.0),
    (54, 0.7, 0.4),
    (80, 1.2, 0.1),
    (64, 0.9, 0.3),
    (52, 1.1, 0.2),
    (68, 0.8, 0.0),
    (44, 1.0, 0.4),
    (58, 1.2, 0.1),
    (40, 0.9, 0.3),
    (50, 1.1, 0.2),
    (34, 0.8, 0.0),
    (28, 1.0, 0.1),
]


def art_shapes() -> tuple[list[str], list[str]]:
    blocks, lines = [], []
    for row, text in enumerate(ART.splitlines()):
        for col, char in enumerate(text):
            x, y = ART_X + col * CELL_W, ART_Y + row * CELL_H
            if char == "█":
                blocks.append(f'<rect x="{x}" y="{y}" width="{CELL_W}" height="{CELL_H}"/>')
            for x1, y1, x2, y2 in SEGMENTS.get(char, []):
                lines.append(
                    f'<line x1="{x + x1 * CELL_W:g}" y1="{y + y1 * CELL_H:g}" '
                    f'x2="{x + x2 * CELL_W:g}" y2="{y + y2 * CELL_H:g}"/>'
                )
    return blocks, lines


def spectrum() -> list[str]:
    bars = []
    for i, (height, duration, delay) in enumerate(BARS):
        x, bottom = 642 + i * 13, 214
        color = "#e8452f" if height >= 80 else "#e8d23a" if height >= 66 else GREEN
        bars.append(
            f'<rect class="bar" x="{x}" y="{bottom - height}" width="9" height="{height}" rx="1.5" '
            f'fill="{color}" style="animation-duration:{duration}s;animation-delay:-{delay}s"/>'
        )
    return bars


def build() -> str:
    blocks, lines = art_shapes()
    nl = "\n    "
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="900" height="280" viewBox="0 0 900 280" role="img" aria-labelledby="title desc">
  <title id="title">PyAmp</title>
  <desc id="desc">PyAmp: a lightweight, Winamp-inspired music player written in Python. Retro LCD header with a spectrum analyser.</desc>
  <!-- Generated by docs/make_header.py; edit that, not this file. -->
  <defs>
    <filter id="glow" x="-10%" y="-30%" width="120%" height="160%">
      <feGaussianBlur stdDeviation="2.2" result="blur"/>
      <feMerge><feMergeNode in="blur"/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
    <pattern id="scan" width="4" height="4" patternUnits="userSpaceOnUse">
      <rect width="4" height="2" fill="#ffffff" opacity="0.025"/>
    </pattern>
    <style>
      .bar {{ transform-box: fill-box; transform-origin: 50% 100%; animation: bounce 1s ease-in-out infinite alternate; }}
      @keyframes bounce {{ from {{ transform: scaleY(0.35); }} to {{ transform: scaleY(1); }} }}
      @media (prefers-reduced-motion: reduce) {{ .bar {{ animation: none; }} }}
      .mono {{ font-family: "SF Mono", Menlo, Consolas, "DejaVu Sans Mono", "Liberation Mono", monospace; }}
    </style>
  </defs>

  <rect width="900" height="280" rx="24" fill="{SLATE}"/>
  <g fill="{GOLD}">
    <rect x="40" y="20" width="300" height="3" rx="1.5"/><rect x="40" y="27" width="300" height="3" rx="1.5"/>
    <rect x="560" y="20" width="300" height="3" rx="1.5"/><rect x="560" y="27" width="300" height="3" rx="1.5"/>
  </g>
  <text x="450" y="31" text-anchor="middle" class="mono" font-size="13" font-weight="700" letter-spacing="4" fill="{GOLD}">PYAMP</text>

  <rect x="24" y="46" width="852" height="210" rx="16" fill="{LCD}"/>

  <g filter="url(#glow)">
    <g stroke="{SHADOW}" stroke-width="{LINE}" stroke-linecap="square" fill="none">
    {nl.join(lines)}
    </g>
    <g fill="{GREEN}">
    {nl.join(blocks)}
    </g>
  </g>

  <text x="{ART_X}" y="236" class="mono" font-size="15" fill="{DIM}">a lightweight, Winamp-inspired music player, written in Python</text>

  <g filter="url(#glow)">
    <path d="M644 72 L644 96 L662 84 Z" fill="{GREEN}" stroke="{GREEN}" stroke-width="3" stroke-linejoin="round"/>
    <text x="676" y="97" class="mono" font-size="34" font-weight="700" fill="{GREEN}">01:23</text>
    {nl.join(spectrum())}
  </g>
  <rect x="642" y="218" width="204" height="2" rx="1" fill="#2a2c3a"/>

  <rect x="24" y="46" width="852" height="210" rx="16" fill="url(#scan)"/>
</svg>
"""


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parents[2])} ({OUT.stat().st_size} bytes)")
