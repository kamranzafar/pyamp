# ruff: noqa: E501  (the SVG template lines are long by nature)

"""Generate the README header, ``docs/assets/pyamp-header.svg``.

    uv run python docs/make_header.py

"PyAmp" is figlet's ANSI Shadow font, drawn as blocks and line segments rather
than SVG text, so it looks the same whatever fonts the viewer has.
"""

from __future__ import annotations

from pathlib import Path

OUT = Path(__file__).resolve().parent / "assets" / "pyamp-header.svg"

ART = """\
██████╗ ██╗   ██╗ █████╗ ███╗   ███╗██████╗
██╔══██╗╚██╗ ██╔╝██╔══██╗████╗ ████║██╔══██╗
██████╔╝ ╚████╔╝ ███████║██╔████╔██║██████╔╝
██╔═══╝   ╚██╔╝  ██╔══██║██║╚██╔╝██║██╔═══╝
██║        ██║   ██║  ██║██║ ╚═╝ ██║██║
╚═╝        ╚═╝   ╚═╝  ╚═╝╚═╝     ╚═╝╚═╝"""

TAGLINE = "A lightweight, Winamp-inspired music player, written in Python."
CELL_W, CELL_H = 12, 22
ART_X, ART_Y = 56, 82
LINE = 3.2  # shadow stroke width
# The app icon's palette (src/pyamp/resources/icon.svg).
SLATE, GOLD, LCD, GREEN, YELLOW, RED = (
    "#2a2c3a",
    "#d4ac4a",
    "#08090b",
    "#22e06b",
    "#e8d23a",
    "#e8452f",
)
SHADOW = "#137a3c"
TEXT, MUTED, BORDER = "#e8e9f0", "#9a9db2", "#3a3d4f"
MONO = "'SF Mono', Menlo, Consolas, 'DejaVu Sans Mono', 'Liberation Mono', monospace"
SANS = "-apple-system, BlinkMacSystemFont, 'Segoe UI', 'Helvetica Neue', Arial, sans-serif"

#: Box-drawing characters as line segments within a cell, as (x1, y1, x2, y2) in 0..1.
SEGMENTS = {
    "═": [(0, 0.5, 1, 0.5)],
    "║": [(0.5, 0, 0.5, 1)],
    "╔": [(1, 0.5, 0.5, 0.5), (0.5, 0.5, 0.5, 1)],
    "╗": [(0, 0.5, 0.5, 0.5), (0.5, 0.5, 0.5, 1)],
    "╚": [(0.5, 0, 0.5, 0.5), (0.5, 0.5, 1, 0.5)],
    "╝": [(0.5, 0, 0.5, 0.5), (0.5, 0.5, 0, 0.5)],
}

#: Spectrum bars: resting height (px); the animation varies them.
BARS = [46, 72, 60, 88, 70, 54, 80, 64, 52, 68, 44, 58, 40, 50, 34, 28]


def art_shapes() -> tuple[list[str], list[str]]:
    blocks, lines = [], []
    for row, text in enumerate(ART.splitlines()):
        for col, char in enumerate(text):
            x, y = ART_X + col * CELL_W, ART_Y + row * CELL_H
            if char == "█":
                blocks.append(f'<rect x="{x}" y="{y}" width="{CELL_W}" height="{CELL_H}"/>')
            for x1, y1, x2, y2 in SEGMENTS.get(char, []):
                lines.append(
                    f'<line x1="{x + x1 * CELL_W:g}" y1="{y + y1 * CELL_H:g}" '
                    f'x2="{x + x2 * CELL_W:g}" y2="{y + y2 * CELL_H:g}"/>'
                )
    return blocks, lines


def spectrum() -> list[str]:
    """Green bars; the tallest get the icon's yellow or red tip."""
    bars = []
    for i, height in enumerate(BARS):
        x, top = 646 + i * 13, 214 - height
        tip = RED if height >= 80 else YELLOW if height >= 66 else None
        style = f"animation-duration:{0.8 + (i * 37 % 6) / 10:.1f}s;animation-delay:-{(i * 13 % 5) / 10:.1f}s"
        cap = f'<rect x="{x}" y="{top}" width="8" height="10" rx="2" fill="{tip}"/>' if tip else ""
        bars.append(
            f'<g class="bar" style="{style}"><rect x="{x}" y="{top}" width="8" height="{height}" rx="2" fill="{GREEN}"/>{cap}</g>'
        )
    return bars


def build() -> str:
    blocks, lines = art_shapes()
    nl = "\n    "
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="900" height="280" viewBox="0 0 900 280" role="img" aria-labelledby="title desc">
  <title id="title">PyAmp</title>
  <desc id="desc">{TAGLINE}</desc>
  <!-- Generated by docs/make_header.py; edit that, not this file. -->
  <defs>
    <linearGradient id="frame" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#30323f"/><stop offset="1" stop-color="{SLATE}"/>
    </linearGradient>
    <linearGradient id="screen" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="{LCD}"/><stop offset="1" stop-color="#0c0d11"/>
    </linearGradient>
    <radialGradient id="glow" cx="0.22" cy="0.3" r="0.55">
      <stop offset="0" stop-color="{GREEN}" stop-opacity="0.10"/><stop offset="1" stop-color="{GREEN}" stop-opacity="0"/>
    </radialGradient>
    <linearGradient id="brand" gradientUnits="userSpaceOnUse" x1="{ART_X}" y1="0" x2="{ART_X + 44 * CELL_W}" y2="0">
      <stop offset="0" stop-color="{GREEN}"/><stop offset="1" stop-color="#4beb8a"/>
    </linearGradient>
    <filter id="soft" x="-10%" y="-30%" width="120%" height="160%">
      <feGaussianBlur stdDeviation="2" result="blur"/>
      <feMerge><feMergeNode in="blur"/><feMergeNode in="SourceGraphic"/></feMerge>
    </filter>
    <style>
      .bar {{ transform-box: fill-box; transform-origin: 50% 100%;
              animation: level 1s ease-in-out infinite alternate; }}
      @keyframes level {{ from {{ transform: scaleY(0.35); }} to {{ transform: scaleY(1); }} }}
      @media (prefers-reduced-motion: reduce) {{ .bar {{ animation: none; }} }}
    </style>
  </defs>

  <rect x="0.5" y="0.5" width="899" height="279" rx="22" fill="url(#frame)" stroke="{BORDER}"/>
  <rect x="390" y="19" width="120" height="6" rx="3" fill="{GOLD}"/>

  <rect x="24.5" y="46.5" width="851" height="209" rx="16" fill="url(#screen)" stroke="{BORDER}"/>
  <rect x="25" y="47" width="850" height="208" rx="16" fill="url(#glow)"/>

  <g filter="url(#soft)">
    <g stroke="{SHADOW}" stroke-width="{LINE}" stroke-linecap="round" fill="none" opacity="0.9">
    {nl.join(lines)}
    </g>
    <g fill="url(#brand)" shape-rendering="crispEdges">
    {nl.join(blocks)}
    </g>
  </g>

  <text x="{ART_X}" y="236" font-family="{SANS}" font-size="15.5" fill="{MUTED}">{TAGLINE}</text>

  <g>
    <path d="M648 74 L648 96 L665 85 Z" fill="{GREEN}" stroke="{GREEN}" stroke-width="3" stroke-linejoin="round"/>
    <text x="678" y="96" font-family="{MONO}" font-size="30" font-weight="600" fill="{TEXT}">01:23</text>
    <text x="780" y="96" font-family="{SANS}" font-size="13" fill="{MUTED}">/ 04:56</text>
    {nl.join(spectrum())}
  </g>
</svg>
"""


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(OUT.parents[2])} ({OUT.stat().st_size} bytes)")
